import { build } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';

const result = await build({
  entryPoints: ['src/client.jsx'], bundle: true, write: false, format: 'cjs',
  platform: 'browser', target: ['chrome120', 'firefox120', 'safari17'],
  external: ['react', 'react-dom'], jsx: 'transform', minify: false,
  legalComments: 'none', charset: 'utf8',
});
const body = result.outputFiles[0].text;
const { version } = JSON.parse(await readFile(new URL('../package.json', import.meta.url), 'utf8'));
const bundle = `/* DSH Quick Prompts v${version} · MIT · generated by npm run build */\nwindow.__ModuleLoader__.load({\n  id: 'dsh-quick-prompts',\n  factory(require) {\n    const module = { exports: {} };\n    const exports = module.exports;\n${body}\n    return module.exports;\n  }\n});\n`;
await mkdir('lib', { recursive: true });
await writeFile('lib/client.js', bundle);
console.log(`Built lib/client.js (${Buffer.byteLength(bundle).toLocaleString()} bytes)`);
